    public PDFProcessor(RepresentableAsPDF rep) {
        this.myRep = rep;
        try {
            this.myRepDefault = (RepresentableDefault) this.myRep;
        } catch (Exception e) {
        }
        
        if (this.myRepDefault != null) {
            this.animationMap = this.myRepDefault.getAnimate();
        } else {
            ArrayList<String> animateThis = new ArrayList<>();
            animateThis.add(RepresentableDefault.THIS_NAME);
            animateThis.add("");
            this.animationMap.put(0, animateThis);
        }
    }
    
    public final String getPlainPDFScript() {
        return this.getCodePrefix() + "\n" + this.getSourceString();
    }
    
